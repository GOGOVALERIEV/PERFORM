missing = [f for f in REQUIRED if f not in full]
fused = [tok for tok in re.findall(r'\S+', full) if len(tok.strip('„“".,!?—()-')) > 22]
print('\nfused:', fused or 'NONE', '| missing:', missing or 'NONE — all 21 facts present')
for i, t in enumerate(texts):
    lens = [len(s.split()) for s in re.split(r'(?<=[.!?])\s+', t) if s.strip()]
    print(f'block-{i+1}: {len(t.split())} words, lens {lens}')
    (OUT / f'block-{i+1}.txt').write_text(t, encoding='utf-8')

